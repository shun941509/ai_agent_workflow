function trainingSkill(slug: string, title: string, description: string, example: string, steps: string[]) {
  const content = [
    '---', 'name: ' + slug, 'description: ' + description, '---', '', '# ' + title, '',
    ...steps.map((step, index) => (index + 1) + '. ' + step),
  ].join('\n');
  return {title, example, content};
}

